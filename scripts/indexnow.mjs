#!/usr/bin/env node
// Submit URLs to IndexNow (Bing, Yandex, Seznam, Naver, Yep...).
// Carried over from the old landing site; the key file lives in public/.
//
// Usage:
//   node scripts/indexnow.mjs --all                 # every <loc> in the live sitemap.xml
//   node scripts/indexnow.mjs --changed <base-sha>  # static pages in public/ changed since <base-sha>
//   node scripts/indexnow.mjs <url-or-path> ...     # explicit URLs / site paths
// Flags:
//   --wait     poll until the key file and each URL are live (for post-deploy runs)
//   --dry-run  print the payload without sending it

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync } from 'node:fs';

const HOST = 'getsonx.com';
const ORIGIN = `https://${HOST}`;
const ENDPOINT = 'https://api.indexnow.org/indexnow';

const keyFile = readdirSync('public').find((f) => /^[0-9a-f]{32}\.txt$/.test(f));
if (!keyFile) throw new Error('IndexNow key file (<32-hex>.txt) not found in public/');
const KEY = readFileSync(`public/${keyFile}`, 'utf8').trim();
const KEY_LOCATION = `${ORIGIN}/${keyFile}`;

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  if (i === -1) return false;
  args.splice(i, 1);
  return true;
};
const wait = flag('--wait');
const dryRun = flag('--dry-run');
const all = flag('--all');
const changedIdx = args.indexOf('--changed');
let changedBase = null;
if (changedIdx !== -1) [, changedBase] = args.splice(changedIdx, 2);

// sitemap.xml is generated by src/app/sitemap.ts, so read the deployed one.
async function sitemapUrls() {
  const res = await fetch(`${ORIGIN}/sitemap.xml`, { cache: 'no-store' });
  if (!res.ok) throw new Error(`sitemap.xml: HTTP ${res.status}`);
  return [...(await res.text()).matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].trim());
}

// Map a static page in public/ to its public URL (see the rewrites in next.config.ts).
function pathToUrl(file) {
  if (!file.startsWith('public/') || !file.endsWith('.html')) return null;
  const path = file.slice('public/'.length);
  if (path.endsWith('/index.html')) return `${ORIGIN}/${path.slice(0, -'index.html'.length)}`;
  return `${ORIGIN}/${path}`;
}

async function changedUrls(base) {
  const out = execFileSync('git', ['diff', '--name-only', '--diff-filter=ACMRD', `${base}..HEAD`], {
    encoding: 'utf8',
  });
  const known = new Set(await sitemapUrls());
  // Deleted pages are submitted too (IndexNow uses that to drop them); anything
  // else must be in the sitemap so drafts or stray files aren't pinged.
  return out
    .split('\n')
    .map((f) => f.trim())
    .filter(Boolean)
    .map((f) => ({ f, u: pathToUrl(f) }))
    .filter(({ f, u }) => u && (known.has(u) || !existsSync(f)))
    .map(({ u }) => u);
}

let urls;
if (all) urls = await sitemapUrls();
else if (changedBase && !/^0+$/.test(changedBase)) urls = await changedUrls(changedBase);
else if (changedBase) urls = await sitemapUrls(); // first push: no base to diff against
else urls = args.map((a) => (a.startsWith('http') ? a : pathToUrl(a) ?? `${ORIGIN}/${a.replace(/^\//, '')}`));
urls = [...new Set(urls)];

if (urls.length === 0) {
  console.log('IndexNow: no URLs to submit.');
  process.exit(0);
}
const foreign = urls.filter((u) => new URL(u).host !== HOST);
if (foreign.length) throw new Error(`URLs outside ${HOST}: ${foreign.join(', ')}`);

async function waitFor(url, check, { tries = 30, delayMs = 10_000 } = {}) {
  for (let i = 1; i <= tries; i++) {
    try {
      const res = await fetch(url, { redirect: 'follow', cache: 'no-store' });
      if (await check(res)) return true;
    } catch {}
    if (i < tries) await new Promise((r) => setTimeout(r, delayMs));
  }
  return false;
}

if (wait && !dryRun) {
  const keyLive = await waitFor(KEY_LOCATION, async (r) => r.ok && (await r.text()).trim() === KEY);
  if (!keyLive) throw new Error(`Key file not live at ${KEY_LOCATION}`);
  // Give the deploy time to serve new pages; deleted pages are expected to 404.
  for (const u of urls) await waitFor(u, (r) => r.status !== 404, { tries: 12 });
}

const payload = { host: HOST, key: KEY, keyLocation: KEY_LOCATION, urlList: urls };
console.log(`IndexNow: submitting ${urls.length} URL(s):\n  ${urls.join('\n  ')}`);
if (dryRun) {
  console.log(JSON.stringify(payload, null, 2));
  process.exit(0);
}

const res = await fetch(ENDPOINT, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json; charset=utf-8' },
  body: JSON.stringify(payload),
});
const reasons = {
  200: 'OK - submitted',
  202: 'Accepted - key validation pending',
  400: 'Bad request - invalid format',
  403: 'Forbidden - key not valid (file missing or content mismatch)',
  422: "Unprocessable - URLs don't belong to host or key doesn't match",
  429: 'Too many requests',
};
console.log(`IndexNow: HTTP ${res.status} ${reasons[res.status] ?? ''}`);
if (res.status >= 300) {
  console.error(await res.text());
  process.exit(1);
}
